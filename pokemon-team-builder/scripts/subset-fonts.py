"""Writes small "core" copies of the app's fonts to src/assets/fonts/, plus fonts.css declaring them.

The Fontsource Latin files carry ~220 glyphs and every OpenType feature (JetBrains Mono's code
ligatures alone are half its file). The core copies keep printable ASCII and the few other
characters the UI uses, with kerning only: 52 KB instead of 112 KB. fonts.css is imported after
the Fontsource CSS, so the browser checks the core faces first and only downloads a full Latin
file when text contains a character the core copy lacks.

Usage (from pokemon-team-builder/, after npm ci):
    pip install fonttools brotli
    python3 scripts/subset-fonts.py
"""
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "assets" / "fonts"

# Printable ASCII, plus the non-ASCII characters in the UI and in common PokeAPI text.
UNICODES = [*range(0x20, 0x7F), *map(ord, "°·¼½×Éé–—‘’“”…←→↗↺−▸")]

FONTS = [
    # (family as declared by Fontsource, weight range, source file under node_modules)
    ("Space Grotesk Variable", "300 700", "@fontsource-variable/space-grotesk/files/space-grotesk-latin-wght-normal.woff2"),
    ("DM Sans Variable", "100 1000", "@fontsource-variable/dm-sans/files/dm-sans-latin-wght-normal.woff2"),
    ("JetBrains Mono Variable", "100 800", "@fontsource-variable/jetbrains-mono/files/jetbrains-mono-latin-wght-normal.woff2"),
    ("Press Start 2P", "400", "@fontsource/press-start-2p/files/press-start-2p-latin-400-normal.woff2"),
]


def unicode_range(codepoints: list[int]) -> str:
    """Collapses sorted codepoints into a CSS unicode-range list."""
    ranges: list[list[int]] = []
    for cp in codepoints:
        if ranges and cp == ranges[-1][1] + 1:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp])
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in ranges)


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    css = ["/* Generated by scripts/subset-fonts.py. Do not edit by hand. */"]
    for family, weight, source in FONTS:
        src = ROOT / "node_modules" / source
        name = src.name.replace("-latin-", "-core-")
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["kern"]
        font = TTFont(src)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=UNICODES)
        subsetter.subset(font)
        font.flavor = "woff2"
        font.save(OUT / name)
        # Declare only the characters the subset actually has, so missing ones fall through.
        covered = sorted(font.getBestCmap().keys())
        css.append(
            "@font-face {\n"
            f"  font-family: '{family}';\n"
            "  font-style: normal;\n"
            "  font-display: swap;\n"
            f"  font-weight: {weight};\n"
            f"  src: url(./{name}) format('woff2');\n"
            f"  unicode-range: {unicode_range(covered)};\n"
            "}"
        )
        print(f"{name}: {src.stat().st_size} -> {(OUT / name).stat().st_size} bytes")
    (OUT / "fonts.css").write_text("\n".join(css) + "\n")


if __name__ == "__main__":
    main()
